"""Итерация 1. Базовая (чистый Python) реализация метода прямоугольников."""

from typing import Callable


def integrate(f: Callable[[float], float], a: float, b: float, *, n_iter: int = 100000) -> float:
    """Вычислить приближённое значение определённого интеграла функции ``f``.

    Использует метод левых прямоугольников: отрезок ``[a, b]`` делится на
    ``n_iter`` равных частей шириной ``step = (b - a) / n_iter``, и интеграл
    приближается суммой площадей прямоугольников, высота которых равна
    значению ``f`` в левом конце каждого подотрезка.

    :param f: интегрируемая функция одной вещественной переменной,
        принимающая ``float`` и возвращающая ``float``.
    :param a: нижний предел интегрирования.
    :param b: верхний предел интегрирования.
    :param n_iter: количество разбиений отрезка ``[a, b]`` (количество
        прямоугольников). Чем больше значение, тем точнее результат, но
        тем дольше вычисление (сложность ``O(n_iter)``).
    :return: приближённое значение интеграла ``f`` на отрезке ``[a, b]``.
    :raises ZeroDivisionError: если ``n_iter == 0``.

    .. note::
        Метод левых прямоугольников имеет первый порядок точности:
        погрешность убывает линейно с ростом ``n_iter``. Для функций с
        большой кривизной или при малых ``n_iter`` погрешность может быть
        существенной.

    >>> import math
    >>> round(integrate(math.sin, 0, math.pi, n_iter=100000), 4)
    2.0

    >>> round(integrate(lambda x: x ** 2, 0, 1, n_iter=100000), 4)
    0.3333
    """
    acc = 0.0
    step = (b - a) / n_iter
    for i in range(n_iter):
        acc += f(a + i * step) * step
    return acc


